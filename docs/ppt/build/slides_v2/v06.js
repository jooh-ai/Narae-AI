const H = [
  ['기각', '2025 상반기는 설비가 달랐다',  'IGV 효과 평균 *+0.09* → 설비가 아니라 _IGV 미실시_'],
  ['기각', '진공 잔차로 예측할 수 있다',   'n=5 에서 −0.85 → *n=40 에서 +0.05* (임계 0.31)'],
  ['기각', '이론값 차이는 진공 항 때문',   '58건 대조 → 차이가 온도에 비례. _곡선 자체의 차이_'],
  ['기각', '여름에만 진공 영향이 보인다',  'n=9 에서 −0.675 → 한 건 빼면 *9번 중 6번* 무의'],
  ['채택', '진공도는 외기온도의 함수다',   '진공도 = 33.43 + 1.261 × 온도, r *+0.952*'],
];
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { sec: '가설 검증', idx: 3, step: 3 });
  T.title(d, '그럴듯한 설명 5개를 의심했고,', '*4개는 틀렸습니다*');
  T.lead(d, '누적 ' + D.n + '건으로 하나씩 검증했습니다. _살아남은 것은 하나_ 입니다.',
         { lines: 1 });

  H.forEach(([v, q, e], i) => {
    const y = 284 + i * 56, ok = v === '채택';
    d.box(G.L, y + 2, 64, 28, null, ok ? '6B5220' : C.redD, 1.4);
    d.text(v, { x: G.L, y: y + 8, w: 64, px: 13.5, lh: 1.2, bold: true,
                color: ok ? C.brass : C.red, align: 'center' });
    d.sub(q, 152, y, 396, 1, ok ? C.brass : C.ink);
    d.txt(e, 568, y + 4, 640, 1);
    if (i < 4) d.hline(G.L, y + 46, G.W, C.rule2, 1);
  });

  /* 이 장의 결론 — 세 번 걸린 것을 코드로 막았다 */
  d.zone(G.L, 566, G.W, 58);
  d.text('같은 변수(진공도)에서 *세 번* 걸렸습니다 — 전부 _부분집합을 잘라 만든 상관_.  ' +
         '그래서 판정을 코드로 옮겼습니다: 안정성 80% 미달이면 *자동 기각*.',
         { x: 96, y: 576, w: 1088, px: 14.5, lh: 1.5, lines: 2, color: C.body,
           align: 'center' });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '남은 설명은 *온도* 하나 — 그리고 틀린 가설을 스스로 걸러내는 절차가 남았습니다.');
};
