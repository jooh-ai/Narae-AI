/* v2-06 · 데이터 분석 및 원인 규명 — 요소 2개: 가설 5행 리스트 / 재발 방지 띠.
   5카드를 세로 리스트로 바꿔 눈이 한 줄씩 따라가게 했다.                */
'use strict';
const H = [
  ['틀림', '작년 상반기는 설비가 달랐다',
   '설비 탓이 아니라 _공기 흡입량 조절을 안 한 것_ 이었습니다 (평균 *+0.09 MW*)'],
  ['틀림', '복수기 진공도를 보면 맞힐 수 있다',
   '5회만 보면 그렇게 보였지만, *' + '40회 전부로 보면 관계가 없었습니다' + '*'],
  ['틀림', '계산값 차이는 진공도 때문이다',
   '*58회를 맞대 보니* 차이는 온도에 비례했습니다 — 계산 곡선 자체의 차이'],
  ['틀림', '여름에만 진공도 영향이 보인다',
   '9회 중 *한 회만 빼도* 결론이 뒤집혔습니다 — 우연입니다'],
  ['맞음', '진공도는 온도에 따라 움직인다',
   '온도를 알면 진공도가 정해집니다 — *온도가 91% 설명*합니다'],
];
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { sec: '가설 검증', idx: 3, step: 3 });
  T.title(d, '그럴듯한 설명 5개를 의심했고,', '*4개는 틀렸습니다*');
  T.lead(d, '차이가 왜 생기는지 하나씩 데이터로 확인했습니다. _남은 것은 온도 하나_ 입니다.',
         { lines: 1 });

  H.forEach(([v, q, e], i) => {
    const y = 284 + i * 56, ok = v === '맞음';
    d.box(G.L, y + 2, 64, 28, null, ok ? '6B5220' : C.redD, 1.4);
    d.text(v, { x: G.L, y: y + 8, w: 64, px: 13.5, lh: 1.2, bold: true,
                color: ok ? C.brass : C.red, align: 'center' });
    d.sub(q, 152, y, 396, 1, ok ? C.brass : C.ink);
    d.txt(e, 568, y + 4, 640, 1);
    if (i < 4) d.hline(G.L, y + 46, G.W, C.rule2, 1);
  });

  /* 이 장의 결론 — 세 번 걸린 것을 코드로 막았다 */
  d.zone(G.L, 566, G.W, 58);
  d.text('같은 것(진공도)에 *세 번* 속았습니다 — _데이터를 골라 뽑으면 없는 관계도 보입니다_.  ' +
         '그래서 이 판단을 사람이 하지 않고 *코드가 하도록* 옮겼습니다.',
         { x: 96, y: 576, w: 1088, px: 14.5, lh: 1.5, lines: 2, color: C.body,
           align: 'center' });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '남은 설명은 *온도* 하나 — 그래서 온도별로 배우기로 했습니다.');
};
