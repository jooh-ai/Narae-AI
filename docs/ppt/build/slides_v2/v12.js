/* v2-12 · Tool 시연 — 요소 2개: 4단계 / 보실 지점 3개.
   화면 캡처 자리표시자를 두지 않는다 — 실물을 띄워 보이는 장이다.        */
'use strict';
const STEP = [
  ['데이터 취득',      '설비에서 값을 그대로 읽어옵니다. 사람이 옮겨 적는 칸이 없습니다.'],
  ['출력 시뮬레이션',  '온도를 넣으면 이론 출력이 나옵니다. 여기까지가 동결된 1층입니다.'],
  ['보정 학습',        '누적 회차로 온도별 보정을 다시 학습하고 방식을 다시 고릅니다.'],
  ['공급가능용량 산정', '신고할 숫자와 그 근거가 함께 나옵니다.'],
];
const SEE = [
  ['입력 칸이 없습니다',   '온도만 있으면 나머지는 도구가 채웁니다'],
  ['숫자 옆에 근거',       '어느 회차로 학습했는지 화면에 표시됩니다'],
  ['회차를 넣으면 즉시',   '재채점·재선정이 그 자리에서 돌아갑니다'],
];
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { sec: 'Tool 시연' });
  T.title(d, '실제로 *돌려 보겠습니다*');
  T.lead(d, '3~4분입니다. _네 단계_ 만 보시면 됩니다.', { y: 158, lines: 1 });

  /* 4단계 */
  d.zone(G.L, 240, G.W, 216);
  STEP.forEach(([k, v], i) => {
    const x = 96 + i * 272;
    d.big(String(i + 1), x, 264, 44, 42, C.brassD);
    d.sub(k, x + 50, 268, 196, 1);
    d.txt(v, x + 50, 308, 196, 4);
    if (i < 3) d.vline(x + 256, 264, 160, C.rule2, 1);
  });

  /* 보실 지점 */
  d.zone(G.L, 480, G.W, 144);
  d.plab('보실 지점', 96, 494, 300);
  SEE.forEach(([k, v], i) => {
    const x = 96 + i * 376;
    d.rect(x, 522, 40, 2, C.brass);
    d.text(k, { x, y: 534, w: 340, px: 17, lh: 1.3, bold: true, color: C.ink });
    d.txt(v, x, 562, 340, 2);
    if (i < 2) d.vline(x + 352, 520, 84, C.rule2, 1);
  });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '입력하는 칸이 아니라, *근거가 붙은 숫자*를 보십시오.');
};
