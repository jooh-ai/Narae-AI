/* v3-11 · 향후 계획.

   2026-09-18 회신이 이 장을 다시 짰다.
     "실적을 쌓아서 더 정확하게를 차트 말고 말로 간단하게 표현하고, 그 이유는
      0.19에서 1.19로 갈때 오차가 늘어난 사유를 설명하기가 어려움.
      milestone 처럼 시간 경과대로 보여주면 좋을것 같은데. 2주마다 실적을
      쌓아서 비어 있는 온도대 별로 표본을 늘리고 그로 인해 오차를 줄이고
      정확도를 높인다. 재차 검증(loocv)을 통해 최적화 회귀모델을 찾는다.
      다른 사업소 적용 방식 내용을 넣어서 입찰을 진행하는 타사업소(파주,
      여주, 하남)에 전파 한다. 년도와 상반기 하반기 등으로 같이 표현."

   학습 곡선(구간별 MAE 막대)을 걷었다. 0.905 → 1.189 로 되올라간 구간이
   있어서 "쌓이면 좋아진다" 는 말과 어긋나 보였고, 그 이유(마지막 구간에
   겨울 시험이 적게 섞였다)는 장표에서 한 줄로 설명하기 어렵다. 회신의
   판단이 맞다 — 변명이 필요한 차트는 장표에 두지 않는다.

   대신 **온도대별 시험 횟수**를 보인다. 같은 이야기(쌓이면 정확해진다)를
   변명 없이 할 수 있는 그림이다. 어디가 비었는지 눈에 바로 보이고, 그게
   그대로 앞으로 할 일이 된다. 숫자는 deck_data.bins (누적 40회 그대로).  */
'use strict';
const PLAN = [
  ['2026 하반기', '위례 정착 · 빈 온도대 채우기',
   '2주마다 시험하고 결과를 도구에 넣습니다. 실적이 얇은 온도대부터 채웁니다 — ' +
   '20~25℃ 는 1회, 15~20℃ 는 3회뿐입니다. 표본이 붙는 만큼 그 온도의 오차가 줄어듭니다.'],
  ['2027 상반기', '신고 구간 전체 실적 확보 · 회귀 모델 재선정',
   '겨울과 여름이 한 번 더 지나면 신고 구간 전체에 실적이 붙습니다. 그 데이터로 후보 ' +
   '7가지를 다시 채점(LOOCV)해 최적 회귀 모델을 다시 고릅니다 — 지금 1등이 계속 1등일 ' +
   '필요는 없습니다.'],
  ['2027 하반기', '입찰하는 다른 사업소로 · 파주 · 여주 · 하남',
   '도구와 절차는 그대로 옮깁니다. 특성 곡선표만 그 사업소 것으로 바꿔 넣으면 됩니다 — ' +
   '곡선은 코드가 아니라 온도 61줄 표 파일로 읽습니다. 보정 곡선은 그 사업소 시험 ' +
   '실적으로 새로 쌓습니다(위례 곡선을 베껴 쓰지 않습니다).'],
  ['2028', '사업소 표준 절차로',
   '시험부터 신고까지의 순서를 표준 절차서로 정리합니다. 담당자가 바뀌어도 같은 숫자가 ' +
   '나오게 하는 것이 마지막 단계입니다.'],
];
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { name: '향후 계획', idx: 7, step: 7 });
  const B = D.bins;

  T.title(d, '향후 계획', null, { px: 33 });
  T.lead(d, '실적을 쌓아 더 정확하게 만들고, 입찰을 하는 다른 사업소로 넓힙니다.',
         { y: 134, lines: 1 });

  /* ── 구획 1 · 지금 어디가 비어 있나 ──────────────────────────────
     막대 높이는 그 온도대에서 한 시험 횟수다. 3회 이하는 주황으로 둔다 —
     '더 쌓아야 하는 자리' 라는 뜻이고, 그게 구획 2 의 첫 항목이 된다.   */
  const y1 = d.section(G.L, 168, G.W, 172, 1, '지금 어디가 비어 있나',
                       '누적 ' + D.n + '회 · 온도대별 시험 횟수');
  const nmax = Math.max(...B.map(b => b.n)), YB = y1 + 90, CW = 156;
  d.hline(92, YB, 1090, C.rule, 1);
  B.forEach((b, i) => {
    const x = 92 + i * CW, thin = b.n <= 3;
    const h = Math.max(4, Math.round(b.n / nmax * 62));
    d.rect(x + 42, YB - h, 44, h, thin ? C.red : C.brass);
    /* 횟수는 막대 바로 위에 붙인다. 한 줄에 몰아 두면 낮은 막대와 숫자가
       멀어져 어느 숫자가 어느 막대인지 눈으로 잇기 어렵다. */
    d.text(String(b.n) + '회', { x, y: YB - h - 20, w: 128, px: 15, lh: 1.2, mono: true,
                                  bold: true, color: thin ? C.red : C.brass,
                                  align: 'center' });
    d.text(b.label, { x, y: YB + 8, w: 128, px: 10.5, lh: 1.2, color: C.dim,
                      align: 'center' });
    if (i < B.length - 1) d.vline(x + 128, y1 + 18, 68, C.rule2, 1);
  });
  d.text('주황은 3회 이하 — 더 쌓아야 하는 온도대입니다. 신고는 −20 ~ 40℃ 전부인데 ' +
         '실적은 −1.9 ~ 37.9℃ 뿐이라, 그 밖은 끝값을 그대로 씁니다.',
         { x: 92, y: y1 + 112, w: 1090, px: 10.5, lh: 1.3, color: C.dim2 });

  /* ── 구획 2 · 단계별 계획 (milestone) ─────────────────────────── */
  const y2 = d.section(G.L, 352, G.W, 288, 2, '단계별 계획', '2026 하반기 → 2028');
  d.vline(218, y2 + 4, 244, C.rule, 1);
  PLAN.forEach(([when, what, why], i) => {
    const y = y2 + i * 64;
    d.text(when, { x: 92, y: y + 2, w: 110, px: 11.5, lh: 1.2, mono: true, bold: true,
                   color: C.brass, align: 'right' });
    d.dot(218, y + 10, 4.5, C.brass);
    d.text(what, { x: 240, y, w: 942, px: 15, lh: 1.25, bold: true, color: C.ink });
    d.text(why, { x: 240, y: y + 22, w: 942, px: 11.5, lh: 1.4, lines: 2, color: C.dim });
  });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '한 번 만들고 끝나는 도구가 아닙니다. 쌓일수록 촘촘해지고, 옮겨 심을 수 있습니다.');
};
