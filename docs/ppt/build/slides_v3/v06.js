/* v3-06 · 해결 방안 도출 (목차 ④ 전반).

   2026-09-18 3차 회신이 6·7·8장을 한꺼번에 다시 짰다.
     "모니터링은 '향후 추이 분석(모니터링 체계 구축)' 이라는 의미인데, 결국
      우리가 만든 모델의 추후 모니터링을 어떻게 하겠다는 의미로 생각된다.
      모델 선정 탭 내용이 모니터링에 들어가는 게 맞는 것 같은데. 지금 모니터링
      에는 산정 Tool 한 회를 돌린 결과가 있는데 이게 모니터링 구축과 관련이
      있다고 생각하는지? 해결 방안에 있는 '도구 안에서 고릅니다' 가 모니터링에
      가는 게 맞는 것 같은데. 그럼 해결 방안에는 무엇이 들어가야 하나?"

   맞는 지적이었다. ⑤ 의 핵심어는 **향후**와 **체계**다. 한 회를 돌린 결과
   화면은 '지금 이렇게 씁니다'(운영 방법)이지 '앞으로 이렇게 지켜보겠다'
   (체계)가 아니다. 그건 ④ 의 산출물이다 — 엑셀 4개가 하던 일이 한 화면에
   들어왔다는 증거이기 때문이다. 그래서 산정 화면을 이 장으로 가져왔고,
   모델 선정 화면은 8장(모니터링)으로 보냈다.

   그리고 이 장은 가이드 제목대로 **방안을 어떻게 도출했나**를 적는다.
   목표가 둘이므로 구획도 둘이다. 목표 ② 의 방안(점 → 곡선 → 표)을 여기에
   두는 이유 — 그것은 '무엇으로 풀지' 이고, '어떤 회귀 모델로 그릴지' 는
   7장의 일이다. 이 장이 질문을 던지고 7장이 답한다.                     */
'use strict';
const A = require('./assets.js');
const WHY_TOOL = [
  ['엑셀 4개는 사람이 손으로 잇는다',
   '파일 사이를 사람이 값으로 잇습니다. 한곳에 넣으면 옮겨 적을 일이 없어집니다.'],
  ['곡선 계산은 엑셀 수식으로 어렵다',
   '온도별 보정 곡선은 엑셀 수식으로 짜기 어렵습니다. 프로그램에서 계산해야 합니다.'],
  ['실적을 쌓아 둘 곳이 필요하다',
   '회차를 쌓아 두고, 늘 때마다 곡선을 다시 그려야 합니다. 파일로는 관리가 되지 않습니다.'],
];
const STEP = [
  ['① 점을 모은다', '시험마다 점 하나가 생깁니다. 가로는 그날 외기온도, 세로는 실제와 계산값의 차이입니다.'],
  ['② 곡선을 그린다', '쌓인 점을 가장 잘 지나는 곡선을 찾습니다. 점이 없는 온도의 값도 이 곡선이 메웁니다.'],
  ['③ 표를 만든다', '곡선에서 영하 20도부터 40도까지 61개 값을 읽어 신고 표를 만듭니다.'],
];
module.exports = (pptx, T, meta, D) => {
  const { C, G, LW } = T;
  const { d } = T.shell(pptx, { name: '해결 방안', idx: 4, step: 4 });
  T.title(d, '해결 방안 도출', null, { px: 33 });
  T.lead(d, '목표는 두 가지였습니다. 각 목표를 무엇으로 풀지 정했습니다.', { y: 134, lines: 1 });

  /* ── 구획 1 · 목표 ① 절차를 하나로 ───────────────────────────── */
  const y1 = d.section(G.L, 168, 556, 216, 1, '목표 ① 절차를 하나로',
                       '왜 도구를 새로 만들었나');
  WHY_TOOL.forEach(([k, v], i) => {
    const y = y1 + i * 48;
    d.rect(92, y + 2, 4, 36, C.brass);
    d.text(k, { x: 110, y, w: 498, px: 13, lh: 1.25, bold: true, color: C.ink });
    d.text(v, { x: 110, y: y + 18, w: 498, px: 10.5, lh: 1.35, lines: 2, color: C.dim });
  });
  d.text('그래서 엑셀을 고치는 대신 *도구 하나로 합쳤습니다*.',
         { x: 92, y: y1 + 148, w: 516, px: 11.5, lh: 1.35, color: C.body });
  d.text('제작사 계산식과 RiMS 취득 방식은 기존 엑셀에 있던 것을 그대로 옮겼습니다.',
         { x: 92, y: y1 + 164, w: 516, px: 11, lh: 1.3, color: C.dim });

  /* ── 구획 2 · 목표 ② 온도별 보정값 — 점 → 곡선 → 표 ─────────────
     작은 그림 셋은 실제 데이터로 그린다. ① 은 시험 40회 점, ② 는 같은 점에
     도구가 배운 곡선을 겹친 것, ③ 은 표의 모양이다. 도형만 쓰고 글자는 아래에
     따로 둔다 — 작은 그림 안의 글자는 어차피 읽히지 않는다.             */
  const y2 = d.section(644, 168, 564, 216, 2, '목표 ② 온도별 보정값', '점 → 곡선 → 표');
  const PR = D.profile.rows;
  STEP.forEach(([k, v], i) => {
    const x = 664 + i * 182;
    d.text(k, { x, y: y2, w: 166, px: 12.5, lh: 1.25, bold: true, color: C.ink });
    d.box(x, y2 + 22, 150, 50, null, C.rule2, 1);
    const X = t => x + 6 + (t + 4) * (138 / 46);
    const Y = c => y2 + 68 - (c + 6) / 20 * 42;
    if (i < 2) {                                   // ① 점 · ② 점 + 곡선
      d.hline(x + 6, Y(0), 138, C.rule2, 1);
      if (i === 1) {
        const seg = PR.filter(r => r.t >= 0 && r.t <= 40);
        for (let j = 0; j < seg.length - 1; j++)
          d.seg(X(seg[j].t), Y(seg[j].corr), X(seg[j + 1].t), Y(seg[j + 1].corr),
                C.brass, LW.main);
      }
      D.scatter.forEach(([t, c]) => {
        if (t < -4 || t > 40) return;
        d.dot(X(t), Y(c), 1.3, i === 1 ? C.slateL : C.body);
      });
    } else {                                       // ③ 표 모양
      d.vline(x + 52, y2 + 26, 42, C.rule2, 1);
      for (let j = 0; j < 6; j++) {
        const yy = y2 + 30 + j * 7;
        d.hline(x + 10, yy, 38, C.steel, 1);
        d.hline(x + 58, yy, 84, j === 0 ? C.brass : C.steel, 1);
      }
    }
    d.text(v, { x, y: y2 + 78, w: 166, px: 10.5, lh: 1.35, lines: 3, color: C.dim });
    if (i < 2) d.text('→', { x: x + 154, y: y2 + 40, w: 24, px: 13, lh: 1.2,
                             color: C.dim2, align: 'center' });
  });
  d.text('어떤 곡선을 쓸지는 다음 장에서 정합니다. 후보 회귀 모델 7가지를 ' +
         '같은 데이터로 시험했습니다.',
         { x: 664, y: y2 + 130, w: 524, px: 11.5, lh: 1.35, lines: 2, color: C.body });

  /* ── 구획 3 · 도구 화면 (합친 결과) ───────────────────────────── */
  const y3 = d.section(G.L, 396, G.W, 244, 3, '도구 화면 · 공급가능용량 산정',
                       '날짜와 시각만 넣고 누른 결과');
  d.img(A.toolWinRunT, 92, y3, 713, 206);
  [['한 화면', '엑셀 4개를 오가던 일이 이 화면 하나로 끝납니다.'],
   ['이론값 · 보정값 · 현실화', '제작사 계산식으로 낸 값, 온도마다 다른 더하는 값, 실제로 신고하는 값.'],
   ['온도 61구간', '표를 그대로 입찰에 씁니다. 손으로 옮기는 값은 없습니다.']]
    .forEach(([k, v], i) => {
      const y = y3 + i * 70;
      d.text(k, { x: 825, y, w: 357, px: 11.5, lh: 1.2, bold: true, color: C.brass });
      d.text(v, { x: 825, y: y + 18, w: 357, px: 11, lh: 1.35, lines: 3, color: C.dim });
    });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '절차는 도구 하나로 합치고, 보정값은 온도별 곡선으로 내기로 정했습니다.');
};
