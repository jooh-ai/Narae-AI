'use strict';
const A = require('./assets.js');
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { name: '개선 방안', idx: 4, step: 4 });
  T.title(d, '개선 방안', null, { px: 33 });
  T.lead(d, '하나는 흩어진 과정을 도구 하나로 합친 것입니다. 다른 하나는 더하는 값을 온도마다 다르게 한 것입니다.',
         { y: 134, lines: 1 });

  /* ── 구획 1 · 바꾼 것 두 가지 — 한 줄씩만 ─────────────────────── */
  const y1 = d.section(G.L, 168, G.W, 80, 1, '바꾼 것 두 가지',
                       '제작사 계산식은 손대지 않았습니다');
  [['흩어진 과정을 합쳤다', '엑셀 4개', '도구 1개', 130],
   ['더하는 값을 온도마다 다르게', '값 1개', '온도별 곡선', 158]]
    .forEach(([k, a, b, bw], i) => {
    const x = 92 + i * 556;
    d.rect(x, y1, 4, 24, C.brass);
    d.text(String(i + 1), { x: x + 16, y: y1 + 2, w: 20, px: 12, lh: 1.2, mono: true,
                            bold: true, color: C.brass });
    d.text(k, { x: x + 40, y: y1, w: 250, px: 15, lh: 1.25, bold: true, color: C.ink });
    const aw = Math.ceil(T.textW(a, 13)) + 4;
    d.text(a, { x: x + 298, y: y1 + 3, w: aw, px: 13, lh: 1.25, color: C.slateL });
    d.text('→', { x: x + 298 + aw + 6, y: y1 + 3, w: 20, px: 12, lh: 1.2, color: C.dim2 });
    d.text(b, { x: x + 298 + aw + 30, y: y1 + 1, w: bw, px: 14.5, lh: 1.25,
                bold: true, color: C.brass });
    if (i === 0) d.vline(x + 536, y1 - 2, 34, C.rule2, 1);
  });

  /* ── 구획 2 · 도구 화면 (출력곡선 비교 탭 · 창 전체) ────────────
     그림 상자를 원본 비율(2680 : 940 = 2.851)에 정확히 맞춘다. imgFit 은
     높이에 걸리면 가운데로 쪼그라들어 좌우에 흰 띠가 남는다 — 미리보기로
     확인한 자리다. 왼쪽에 붙이고 남는 오른쪽 칸에 읽는 법을 적는다.     */
  const y2 = d.section(G.L, 260, G.W, 380, 2, '도구 화면 · 출력곡선 비교', '');
  d.img(A.toolWinCurve, 92, y2, 900, 316);
  [['위 칸', '이론값(점선)과 도구가 신고하는 값(빨간 선)'],
   ['아래 칸', '온도마다 더할 값(보정값)과 시험 실적 점'],
   ['읽는 법', '두 선이 벌어진 만큼이 그 온도에서 더하는 값입니다']]
    .forEach(([k, v], i) => {
      const y = y2 + i * 96;
      d.text(k, { x: 1012, y, w: 170, px: 11, lh: 1.2, bold: true, color: C.brass });
      d.text(v, { x: 1012, y: y + 18, w: 170, px: 11, lh: 1.4, lines: 4, color: C.dim });
    });
  d.text('* 이 보정 곡선을 무엇으로 그리는지 — 후보 회귀 모델 7가지를 겨루게 해서 고른 ' +
         '과정은 다음 장에 있습니다.',
         { x: 92, y: y2 + 322, w: 1090, px: 10, lh: 1.35, color: C.dim2 });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '제작사 계산식을 그대로 두었으니 다른 발전소에도 옮겨 심을 수 있습니다.');
};
