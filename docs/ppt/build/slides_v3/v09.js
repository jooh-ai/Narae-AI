/* v3-09 · 개선효과 (정성).

   2026-09-17 회신이 이 장을 다시 짰다.
     "정성적 효과 같은데, 뭔가 잘 읽히지 않고 내용이 잘 이해가 가지 않음.
      다른 측면에서 정성적 효과로 넣을 만한게 있을지 검토."

   종전 판은 세 항목마다 '전' 두 줄 · '후' 두 줄을 달아 문단이 여섯 개였다.
   정성 효과는 원래 눈에 잘 안 보이는데 글까지 많으니 읽히지 않는 게 당연했다.

   그래서 **가장 크게 달라진 것 하나**를 골라 도구 화면으로 먼저 보이고
   (시험 전에 미리 가늠한다 — 종전에는 없던 능력이다), 나머지는 한 줄짜리
   카드 셋으로 줄였다. 화면 캡처는 `ui_shots.py` 가 오프스크린으로 실제
   계산을 돌려 잡은 것이고, 장표에서 글자가 읽히도록 결과 칸만 오렸다.    */
'use strict';
const A = require('./assets.js');
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { name: '개선효과', idx: 6, step: 6 });

  T.title(d, '개선 효과 · 정성', null, { px: 33 });
  T.lead(d, '숫자로 적기 어렵지만 일하는 방식에서 달라진 것들입니다.',
         { y: 134, lines: 1 });

  /* ── 구획 1 · 종전에는 없던 능력 — 시험 전에 미리 가늠한다 ────── */
  const y1 = d.section(G.L, 174, G.W, 292, 1, '시험 전에 미리 가늠한다',
                       '도구 화면 · 외기온도 30℃ 로 미리 돌려 본 결과');
  d.imgFit(A.toolSimOut, 92, y1 + 2, 660, 232);
  d.vline(790, y1, 216, C.rule2, 1);
  [['전에는', '시험이 끝나야 그날 숫자를 알았습니다.', C.slateL],
   ['지금은', '온도와 대기압만 넣으면 그 조건의 신고값이 바로 나옵니다.', C.brass]]
    .forEach(([k, v, col], i) => {
      const y = y1 + i * 70;
      d.text(k, { x: 818, y, w: 90, px: 12, lh: 1.2, bold: true, color: col });
      d.text(v, { x: 818, y: y + 20, w: 370, px: 13.5, lh: 1.45, lines: 2,
                  color: i ? C.ink : C.dim });
    });
  d.text('시험 계획을 세울 때 먼저 대 보고, 시험 결과가 이상하면 조건을 바꿔 가며 ' +
         '어디가 어긋났는지 짚어 봅니다.',
         { x: 818, y: y1 + 150, w: 370, px: 12, lh: 1.4, lines: 4, color: C.body });

  /* ── 구획 2 · 그 밖에 달라진 것 ───────────────────────────────── */
  const y2 = d.section(G.L, 478, G.W, 162, 2, '그 밖에 달라진 것', '');
  [['사람이 놓치던 것을 도구가 본다',
    '출력을 끝까지 올리지 않은 시험, 배우지 않은 온도, 일부만 골라 만든 관계 — ' +
    '세 가지를 도구가 걸러냅니다.'],
   ['숫자의 근거가 남는다',
    '전에는 관행으로만 설명했습니다. 지금은 시험 ' + D.n +
    '회 가운데 어느 회차가 어떻게 쓰였는지 화면에 남습니다.'],
   ['담당자가 바뀌어도 같다',
    '엑셀을 다루는 손버릇에 따라 결과가 달라질 수 있었습니다. 지금은 절차가 ' +
    '도구 안에 있습니다.']]
    .forEach(([k, v], i) => {
      const x = 92 + i * 368;
      d.rect(x, y2 + 2, 4, 22, C.brass);
      d.text(k, { x: x + 16, y: y2, w: 330, px: 14.5, lh: 1.25, bold: true, color: C.ink });
      d.text(v, { x: x + 16, y: y2 + 26, w: 330, px: 11.5, lh: 1.4, lines: 4, color: C.dim });
      if (i < 2) d.vline(x + 352, y2 - 2, 108, C.rule2, 1);
    });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '숫자 말고도, 일하는 방식이 사람 손에서 도구 쪽으로 옮겨 왔습니다.');
};
