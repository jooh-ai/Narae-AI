/* v3-09 · 개선효과 (정성).

   2026-09-17 2차 회신: "시험 전에 미리 가늠한다 에서도 Tool 기능인 것처럼
   캡쳐 범위를 넓게 하고 색은 밝게."

   그래서 결과 칸만 오린 그림을 걷고 **창 전체**를 넣었다. 제목줄과 탭줄이
   보여야 "도구에 있는 기능" 으로 읽힌다. 순서도 바꿨다 — 가장 크게 달라진
   것(종전에는 없던 능력)을 위에 두고, 나머지 셋을 아래 한 줄 카드로 둔다. */
'use strict';
const A = require('./assets.js');
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { name: '개선효과', idx: 6, step: 6 });

  T.title(d, '개선 효과 · 정성', null, { px: 33 });
  T.lead(d, '숫자로 적기 어렵지만 일하는 방식에서 달라진 것들입니다.',
         { y: 134, lines: 1 });

  /* ── 구획 1 · 시험 전에 미리 가늠한다 (도구 「출력 시뮬레이션」 창) ── */
  /* 상자는 원본 비율(2680 : 888 = 3.018)에 맞춘다 — imgFit 에 맡기면 높이에
     걸려 가운데로 쪼그라들고 좌우에 흰 띠가 남는다. */
  const y1 = d.section(G.L, 168, G.W, 380, 1, '시험 전에 미리 가늠한다',
                       '도구 화면 · 출력 시뮬레이션');
  d.text('온도와 대기압을 넣으면 그 조건의 이론값 · 더하는 값 · 신고값이 한 번에 나옵니다.',
         { x: 92, y: y1 - 2, w: 940, px: 12, lh: 1.35, color: C.body });
  d.img(A.toolWinSim, 92, y1 + 22, 940, 311);
  [['전에는', '시험이 끝나야 그날 숫자를 알았습니다.', C.slateL],
   ['지금은', '시험 전에 미리 계산해 봅니다.', C.brass],
   ['쓰는 때', '시험 계획을 세울 때, 그리고 결과가 이상할 때.', C.dim2]]
    .forEach(([k, v, col], i) => {
      const y = y1 + i * 104;
      d.text(k, { x: 1046, y, w: 136, px: 11.5, lh: 1.2, bold: true, color: col });
      d.text(v, { x: 1046, y: y + 18, w: 136, px: 11, lh: 1.4, lines: 5, color: C.dim });
    });

  /* ── 구획 2 · 그 밖에 달라진 것 ───────────────────────────────── */
  const y2 = d.section(G.L, 560, G.W, 80, 2, '그 밖에 달라진 것', '');
  [['사람이 놓치던 것을 도구가 본다', '잘못된 시험 세 가지를 도구가 걸러냅니다.'],
   ['숫자의 근거가 남는다', '어느 회차가 어떻게 쓰였는지 화면에 남습니다.'],
   ['담당자가 바뀌어도 같다', '절차가 도구 안에 들어 있습니다.']]
    .forEach(([k, v], i) => {
      const x = 92 + i * 368;
      d.rect(x, y2 + 2, 4, 18, C.brass);
      d.text(k, { x: x + 16, y: y2, w: 330, px: 13.5, lh: 1.25, bold: true, color: C.ink });
      d.text(v, { x: x + 16, y: y2 + 20, w: 330, px: 11, lh: 1.3, color: C.dim });
      if (i < 2) d.vline(x + 352, y2 - 2, 44, C.rule2, 1);
    });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '숫자 말고도, 일하는 방식이 사람 손에서 도구 쪽으로 옮겨 왔습니다.');
};
