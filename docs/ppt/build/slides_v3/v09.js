/* v3-08 · 막혔던 것과 푼 방법 — 과정 전용 장.
   구획 셋을 세로로 놓고, 각 줄을 「막혔던 것 → 한 일 → 그래서」 세 칸으로 읽게 한다.
   말투를 일부러 담담하게 둔다. 고생을 강조하면 오히려 힘이 빠진다.          */
'use strict';
const STORY = [
  ['사내 시스템에서 값을 어떻게 받아오나',
   '기존 엑셀에 붙어 있던 기능을 뜯어 봤습니다. 시작 시각을 한 칸에 넣으면 ' +
   '그때부터 한 시간 평균을 채우는 구조였습니다. 도구가 같은 방식으로 받아오게 했습니다.',
   '값을 자동으로 받습니다',
   '값이 늦게 오는 문제, 뽑는 방법에 따라 값이 다른 문제가 또 있었습니다. ' +
   '32회분을 양쪽으로 뽑아 맞는 쪽을 정했습니다.'],
  ['시험이 적어서 곡선을 믿을 수 있나',
   '한 회를 가리고 나머지로 그 회를 맞혀 보게 했습니다. 이 검사를 도구에 넣어 ' +
   '시험이 쌓일 때마다 다시 돌립니다.',
   '쌓일 때마다 다시 검사합니다',
   '중간에 엉뚱한 구간까지 맞추고 있던 것을 찾았습니다. 그 탓에 0~4도 값이 ' +
   '2.25 MW 부풀려져 있었습니다.'],
  ['우리가 만든 계산이 맞는지',
   '기존 엑셀과 답이 같은지 하나씩 맞춰 봤습니다. 다르면 왜 다른지 찾았습니다.',
   '여섯 군데를 고쳤습니다',
   '믿을 만한 정도를 잘못 계산한 것, 비교 기준이 틀린 것, 파일이 어떤 모양에서 ' +
   '깨지는 것 등입니다. 우리 지적이 오독이었던 것도 찾아 고쳤습니다.'],
];
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const A = require('./assets.js');
  const { d } = T.shell(pptx, { name: '넘어온 과정', idx: 6, step: 6 });
  T.title(d, '막혔던 것과 푼 방법', null, { px: 33 });
  T.lead(d, '해 본 적 없는 일이라 막히는 데가 많았습니다. 세 가지가 특히 오래 걸렸습니다.',
         { y: 146, lines: 1 });

  STORY.forEach(([q, did, got, more], i) => {
    const y = 188 + i * 146;
    d.section(G.L, y, G.W, 136, i + 1, q, '');
    d.text('한 일', { x: 92, y: y + 40, w: 60, px: 11, lh: 1.2, bold: true, color: C.dim2 });
    d.text(did, { x: 92, y: y + 58, w: 520, px: 12.5, lh: 1.5, lines: 4, color: C.body });
    d.vline(640, y + 38, 84, C.rule2, 1);
    d.text('그래서', { x: 664, y: y + 40, w: 60, px: 11, lh: 1.2, bold: true,
                        color: C.brass });
    d.text(got, { x: 664, y: y + 56, w: 250, px: 15, lh: 1.35, lines: 2, bold: true,
                  color: C.brass });
    d.vline(936, y + 38, 84, C.rule2, 1);
    if (i === 1) {
      /* 말로 "검사를 도구에 넣었다" 고만 하면 안 믿긴다. 그 화면을 보여 준다. */
      d.imgFit(A.toolMod, 960, y + 36, 232, 88);
      d.text('도구에 넣은 그 검사 화면입니다.',
             { x: 960, y: y + 126, w: 232, px: 10.5, lh: 1.2, color: C.dim2 });
    } else {
      d.text(more, { x: 960, y: y + 40, w: 232, px: 11.5, lh: 1.45, lines: 6,
                     color: C.dim });
    }
  });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '막힌 자리마다 도구에 검사를 하나씩 심어 두었습니다.');
};
