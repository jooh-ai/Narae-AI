/* v3-07 · 병행 운전과 재검사.

   2026-09-17 2차 회신.
     "3 쌓일 때마다 다시 검사에서 왜 다시 검사하는지와 어떻게 다시 검사하는지에
      대한 텍스트가 위에 있고, 아래에 Tool 캡쳐 이미지가 보이도록 수정하고
      현재 방법이 3개 밖에 안보이는데, 더 보이도록 수정하고 현재는 RMSE 까지만
      보이는 R2 편차 등 데이터가 다 보이면 좋겠음."

   그대로 했다. 왜 / 어떻게를 위에 한 줄씩 두고, 아래에 「모델 선정」 창을
   통째로 넣는다. 후보 7가지 전부와 MAE · RMSE · R² · 편차 · 과대 · 판정
   열이 모두 보인다. 창의 머리(제목·탭)와 표만 남기고 사이의 빈 자리를
   걷어냈다 — `crop_shot.py --stack`.

   한 회차 순서와 병행 운전 결과는 한 구획으로 합쳤다. 캡처에 자리를 주려면
   구획 하나를 줄여야 했고, 둘은 같은 이야기(한 회가 어떻게 도는가)다.     */
'use strict';
const A = require('./assets.js');
const STEP = [
  ['시험한다', '2주마다 테스트를 합니다.'],
  ['날짜·시각을 넣는다', 'RiMS 에서 도구가 받아옵니다.'],
  ['그날의 차이가 쌓인다', '실제 − 계산 = 점 하나가 늘어납니다.'],
  ['곡선을 다시 그린다', '쌓인 점 전부로 곡선을 다시 그립니다.'],
  ['다음 신고에 쓴다', '온도 61개 표를 새로 만듭니다.'],
];
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { name: '모니터링', idx: 5, step: 5 });
  const CM = D.commission;

  T.title(d, '넉 달 병행 운전', null, { px: 33 });
  T.lead(d, '기존 방식과 나란히 돌렸습니다. 예측을 먼저 적어 두고 시험이 끝난 뒤 실제와 맞춰 봤습니다.',
         { y: 134, lines: 1 });

  /* ── 구획 1 · 한 회차 순서 + 병행 운전 결과 ───────────────────── */
  const y1 = d.section(G.L, 168, G.W, 128, 1, '한 회차 순서', '2주에 한 번');
  STEP.forEach(([k, v], i) => {
    const x = 92 + i * 222;
    d.text(String(i + 1), { x, y: y1, w: 18, px: 13, lh: 1.2, mono: true, bold: true,
                            color: C.brass });
    d.text(k, { x: x + 22, y: y1 - 2, w: 178, px: 13.5, lh: 1.25, bold: true, color: C.ink });
    d.text(v, { x: x + 22, y: y1 + 20, w: 178, px: 11, lh: 1.35, lines: 2, color: C.dim });
    if (i < 4) d.text('→', { x: x + 200, y: y1, w: 18, px: 12, lh: 1.2, color: C.dim2,
                             align: 'center' });
  });
  d.hline(92, y1 + 62, 1090, C.rule2, 1);
  d.text('병행 운전', { x: 92, y: y1 + 70, w: 90, px: 11.5, lh: 1.2, bold: true,
                         color: C.brass });
  d.text(CM.from + ' ~ ' + CM.to + ' 에 *' + CM.n + '회*. 평균 어긋난 폭은 *' +
         CM.mae.toFixed(2) + ' MW*, 치우침은 ' + CM.me.toFixed(2) +
         ' MW 로 한쪽으로 쏠리지 않았습니다.',
         { x: 190, y: y1 + 70, w: 992, px: 12.5, lh: 1.3, color: C.body });

  /* ── 구획 2 · 한 회를 돌린 결과 (도구 「공급가능용량 산정」 창) ──
     2026-09-18 회신으로 모델 선정 화면은 7장(회귀 모델 선정)으로 옮겼다.
     이 장에는 실제로 한 회차를 돌리면 나오는 화면을 넣는다 — 모니터링은
     '무엇을 고르나' 가 아니라 '어떻게 도나' 를 보이는 자리다.
     상자는 원본 비율(2680 : 774 = 3.463)에 맞춘다.                     */
  const y2 = d.section(G.L, 308, G.W, 332, 2, '한 회를 돌린 결과',
                       '도구 화면 · 날짜와 시각만 넣고 산정을 누른 결과');
  d.img(A.toolWinRunT, 92, y2, 940, 271);
  [['이론값', '제작사 계산식으로 낸 값'],
   ['보정값', '온도마다 다른 더할 값'],
   ['현실화', '실제로 신고하는 값']]
    .forEach(([k, v], i) => {
      const y = y2 + 6 + i * 80;
      d.text(k, { x: 1046, y, w: 136, px: 11.5, lh: 1.2, bold: true, color: C.brass });
      d.text(v, { x: 1046, y: y + 18, w: 136, px: 11, lh: 1.35, lines: 3, color: C.dim });
    });
  d.text('온도 61구간이 한 표에 나옵니다. 이 표를 그대로 입찰에 씁니다. ' +
         '쌓인 실적으로 곡선을 다시 고르는 화면은 7장에 있습니다.',
         { x: 92, y: y2 + 278, w: 1090, px: 11, lh: 1.3, color: C.dim2 });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '책상 계산이 아니라, 넉 달을 기존 방식과 나란히 돌려 확인한 결과입니다.');
};
