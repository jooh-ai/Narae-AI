/* v3-07 · 병행 운전과 재검사.

   2026-09-17 회신이 이 장을 고쳤다.
     "1. 한 회차가 도는 순서에서 말의 의미 명확하도록 수정.
      3. 잘못된 회차를 걸러내는 내용 이해가 잘 안 간다. 궂이 넣어야 하는지?
      결론 멘트 이상함."

   ① 순서는 네 칸에 짧은 말만 적어 두었더니 무슨 뜻인지 물어야 알 수 있었다.
      다섯 칸으로 늘리고 칸마다 한 줄 설명을 붙였다.
   ② 걸러내는 장치는 뺐다. 같은 내용이 9장(정성 효과 · 리스크 저감)에 또 있어
      두 번 말하고 있었다. 그 쪽이 제자리다.
   ③ 빈 자리에 도구의 「모델 선정」 화면을 넣었다. 실적이 늘 때마다 후보를
      다시 겨루게 하는 기능이고, 회신에서 "loocv 기능도 캡쳐해서 흐름에 맞게
      넣으면 좋겠다" 고 한 그 화면이다.                                     */
'use strict';
const A = require('./assets.js');
/* 칸 폭이 176px 이다. 11px 한글이 한 줄에 16자쯤 들어가므로 문장을 32자
   안쪽으로 맞춘다 — 넘기면 마지막 한두 글자만 다음 줄로 떨어진다. */
const STEP = [
  ['시험한다', '2주마다 한 번 테스트를 합니다.'],
  ['날짜·시각을 넣는다', '계측값은 도구가 받아옵니다.'],
  ['그날의 차이가 쌓인다', '실제 − 계산 = 점 하나가 늘어납니다.'],
  ['곡선을 다시 그린다', '쌓인 점 전부로 곡선을 다시 그립니다.'],
  ['다음 신고에 쓴다', '온도 61개 표를 새로 만듭니다.'],
];
module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { name: '모니터링', idx: 5, step: 5 });
  const CM = D.commission;

  T.title(d, '넉 달 병행 운전', null, { px: 33 });
  T.lead(d, '기존 방식과 나란히 돌렸습니다. 예측을 먼저 적어 두고 시험이 끝난 뒤 실제와 맞춰 봤습니다.',
         { y: 134, lines: 1 });

  /* ── 구획 1 · 한 회차 순서 ────────────────────────────────────── */
  const y1 = d.section(G.L, 168, G.W, 104, 1, '한 회차 순서', '2주에 한 번');
  STEP.forEach(([k, v], i) => {
    const x = 92 + i * 222;
    d.text(String(i + 1), { x, y: y1, w: 18, px: 13, lh: 1.2, mono: true, bold: true,
                            color: C.brass });
    d.text(k, { x: x + 22, y: y1 - 2, w: 178, px: 13.5, lh: 1.25, bold: true, color: C.ink });
    d.text(v, { x: x + 22, y: y1 + 20, w: 178, px: 11, lh: 1.35, lines: 3, color: C.dim });
    if (i < 4) d.text('→', { x: x + 200, y: y1, w: 18, px: 12, lh: 1.2, color: C.dim2,
                             align: 'center' });
  });

  /* ── 구획 2 · 병행 운전 결과 ──────────────────────────────────── */
  const y2 = d.section(G.L, 282, G.W, 104, 2, '병행 운전 결과',
                       CM.from + ' ~ ' + CM.to);
  [['병행 운전', '4', '개월'], ['맞춰 본 회차', String(CM.n), '회'],
   ['평균 어긋난 폭', CM.mae.toFixed(2), 'MW'],
   ['치우침', CM.me.toFixed(2), 'MW · 한쪽으로 쏠리지 않음']]
    .forEach(([k, v, u], i) => {
      const x = 92 + i * 274;
      d.text(k, { x, y: y2, w: 250, px: 11.5, lh: 1.2, color: C.dim2 });
      const nw = Math.ceil(T.textW(v, 24)) + 4;
      d.text(v, { x, y: y2 + 16, w: nw, px: 24, lh: 1.15, mono: true, bold: true,
                  color: C.brass });
      d.text(u, { x: x + nw + 6, y: y2 + 26, w: 250 - nw - 6, px: 11, lh: 1.25,
                  color: C.dim });
      if (i < 3) d.vline(x + 258, y2 - 2, 44, C.rule2, 1);
    });

  /* ── 구획 3 · 쌓일 때마다 다시 검사 (도구 「모델 선정」 화면) ──── */
  const y3 = d.section(G.L, 396, G.W, 244, 3, '쌓일 때마다 다시 검사',
                       '도구 화면 · 실적이 늘면 후보를 다시 겨룬다');
  d.imgFit(A.toolLoocv, 92, y3 + 4, 1090, 160);
  d.text('* 도구의 「모델 선정」 화면입니다. 후보 7가지 가운데 성적이 좋은 3개와 판정 열만 ' +
         '오려 넣었습니다(원본 픽셀 그대로). 이 화면은 실적의 20% 를 시험지로 따로 떼어 ' +
         '두므로 채점에 쓴 회차가 32회로 적힙니다.',
         { x: 92, y: y3 + 172, w: 1090, px: 10, lh: 1.35, lines: 2, color: C.dim2 });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '넉 달을 나란히 돌려 확인했고, 실적이 늘 때마다 도구가 스스로 다시 채점합니다.');
};
