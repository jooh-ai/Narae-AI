/* 슬라이드 8 · 가설 검증 — 5개 세우고 4개 기각 ★핵심
   계획서 §6 '가설 검증 5건' 그대로. 수치는 tool/scripts/vacuum_check.py 의 출력이다
   (계산이 아니라 검정 기록이므로 deck_data 가 아니라 여기 적는다).

   이 장의 메시지는 결과가 아니라 태도다. 특히 진공도는 같은 변수에서 세 번
   걸렸고, 그 재발을 코드로 막은 것이 이 장의 결론이다.                        */
'use strict';
const H = [
  { v: '기각', q: '2025 상반기는\n설비가 달랐다',
    e: 'IGV 효과 평균 *+0.09*. 설비가 아니라 _IGV 미실시_ 가 원인이었다.' },
  { v: '기각', q: '진공 잔차로\n예측할 수 있다',
    e: 'n=5 에서 r −0.85 → *n=40 에서 +0.05* (임계 0.31). 표본 5개의 과대해석.' },
  { v: '기각', q: '이론값 차이는\n진공 항 때문이다',
    e: '58건 대조 → 차이가 온도에 비례. 진공이 아니라 _곡선 자체의 차이_.' },
  { v: '기각', q: '여름에만\n진공 영향이 보인다',
    e: 'n=9 에서 r −0.675 (임계 0.666). 한 건 빼면 *9번 중 6번* 유의성 상실.' },
  { v: '채택', q: '진공도는\n외기온도의 함수다',
    e: '진공도 = 33.43 + 1.261 × 온도, r *+0.952*. 40건, 분산의 91%.' },
];

module.exports = (pptx, T, meta, D) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { sec: '가설 검증', idx: 3, step: 3 });

  T.title(d, '그럴듯한 설명 5개를 의심했고,', '*4개는 틀렸습니다*');
  T.lead(d, '온도에 따라 갈리는 이유를 설명할 후보를 세우고 누적 ' + D.n +
         '건으로 하나씩 검증했습니다. _살아남은 것은 하나_ 입니다.');

  H.forEach((h, i) => {
    const x = 72 + i * 231, ok = h.v === '채택';
    d.panel(x, 284, 212, ok ? 'on' : 'bad');
    d.plab('가설 ' + (i + 1), x, 298, 212, ok ? C.brass : C.red);
    d.sub(h.q, x, 320, 212, 2);
    d.box(x, 392, 70, 30, null, ok ? '6B5220' : C.redD, 1.4);
    d.text(h.v, { x, y: 399, w: 70, px: 14, lh: 1.2, bold: true,
                  color: ok ? C.brass : C.red, align: 'center' });
    d.txt(h.e, x, 436, 212, 5);
  });

  /* 이 장의 결론 — 세 번 걸린 것을 숨기지 않고 코드로 막았다 */
  d.zone(G.L, 578, G.W, 48);
  d.text('같은 변수(진공도)에서 *세 번* 걸렸습니다 — 전부 _부분집합을 잘라 만든 상관_ 이었습니다.   ' +
         '그래서 판정을 사람 눈에서 코드로 옮겼습니다: 부분집합 결과는 *임계값·안정성과 함께만* 찍히고, ' +
         '안정성 80% 미달이면 자동으로 기각입니다.',
         { x: 96, y: 590, w: 1088, px: 13.5, lh: 1.5, color: C.body, lines: 2 });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '남은 설명은 *온도* 하나였습니다 — 그리고 틀린 가설을 스스로 걸러내는 절차가 남았습니다.');
};
