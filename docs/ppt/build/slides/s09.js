/* 슬라이드 8 · 해결 구조 — 이론은 동결, 통계만 학습
   2단 구조. 위층(이론)은 손대지 않고 아래층(실적 보정)만 데이터가 갱신한다.
   이 분리가 수평 전개(슬라이드 15)의 근거가 된다.                          */
'use strict';
module.exports = (pptx, T) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { sec: '해결 구조', idx: 4, step: 4 });

  T.title(d, '물리 이론은 손대지 않고,', '*차이만* 온도별로 학습합니다');
  T.lead(d, '이론 계산은 검증된 그대로 동결합니다. 학습하는 것은 _이론과 실제의 차이_ 뿐이고, 그 차이를 온도별로 나눠 봅니다.');

  /* 좌 — 2단 구조 */
  const LX = 72, LW = 740;
  d.panel(LX, 288, LW, null);
  d.plab('2단 구조', LX, 302, LW);

  d.zone(LX, 322, LW, 118);
  d.rect(LX, 322, LW, 2, C.slate);
  d.plab('1층  ·  동결 — 손대지 않는다', LX + 16, 336, 400, C.slate);
  d.sub('온도·대기압·습도·진공도로 계산하는 ~이론 출력~', LX + 16, 358, 700, 1, C.ink);
  d.txt('제작사 성능 곡선과 사내 검증을 거친 계산식입니다. 데이터가 쌓여도 바뀌지 않습니다.',
        LX + 16, 396, 700, 1);

  d.text('↓', { x: LX + 16, y: 446, w: 30, px: 18, lh: 1.2, color: C.brass });
  d.text('이론과 실제의 차이', { x: LX + 52, y: 450, w: 300, px: 13, lh: 1.3, color: C.dim });

  d.zone(LX, 478, LW, 118);
  d.rect(LX, 478, LW, 2, C.brass);
  d.plab('2층  ·  학습 — 데이터가 갱신한다', LX + 16, 492, 400, C.brass);
  d.sub('온도별로 나눠 학습하는 *보정값*', LX + 16, 514, 700, 1);
  d.txt('회차가 쌓이면 다시 학습해 값을 갱신합니다. 사람이 정하는 상수는 여기에 없습니다.',
        LX + 16, 552, 700, 1);

  /* 우 — 결과와 이유 */
  d.panel(852, 288, 356, 'on');
  d.plab('최종 신고값', 852, 302, 356);
  d.zone(852, 322, 356, 96);
  d.text('이론 출력', { x: 868, y: 340, w: 324, px: 15, lh: 1.4, color: C.ink });
  d.text('+  온도별 보정값', { x: 868, y: 366, w: 324, px: 15, lh: 1.4, bold: true, color: C.brass });
  d.hline(868, 392, 324, C.rule, 1);
  d.text('=  주간 신고값', { x: 868, y: 396, w: 324, px: 15, lh: 1.4, color: C.ink });

  d.sub('왜 굳이 *둘로 나눴나*', 852, 436, 356, 1);
  [['검증된 이론을 흔들지 않는다', '이론이 틀렸다는 말을 하지 않아도 된다'],
   ['틀린 원인을 찾을 수 있다', '이론 문제인지 보정 문제인지 갈린다'],
   ['다른 사업소에 옮길 수 있다', '이론만 갈아끼우면 2층은 그대로다']]
    .forEach(([k, v], i) => {
      const y = 478 + i * 48;
      d.text('· ' + k, { x: 852, y, w: 356, px: 14, lh: 1.35, bold: true, color: C.ink });
      d.text(v, { x: 866, y: y + 21, w: 342, px: 12.5, lh: 1.35, color: C.dim });
    });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '이론은 그대로 두고 *차이만 배웁니다* — 그래서 다른 사업소로 옮길 수 있습니다.');
};
