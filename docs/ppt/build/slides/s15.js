/* 슬라이드 14 · 정성 효과 — 숫자보다 오래 남는 것
   재현성·추적성·이관성·확장성을 쉬운 말로 바꿔 4분면에 놓는다.
   이 발표의 축은 정확도 개선이 아니라 '판단의 근거화' 다.                   */
'use strict';
module.exports = (pptx, T) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { sec: '정성 효과', idx: 6, step: 6 });

  T.title(d, '숫자보다 오래 남는 것은,', '*설명할 수 있게 됐다*는 점입니다');
  T.lead(d, 'MW 개선치는 회차마다 달라집니다. 그러나 _왜 그 숫자인지 말할 수 있게 된 것_ 은 되돌아가지 않습니다.');

  [{ lab: '재현성', t: '다시 해도 *같은 답*이 나옵니다',
     v: '같은 데이터와 같은 코드면 누가 돌려도 같은 값입니다. 사람의 판단이 끼어들 자리가 없습니다.' },
   { lab: '추적성', t: '*왜 그 값인지* 되짚을 수 있습니다',
     v: '회차마다 취득 시각·검증 통과 여부·선택된 방식이 남습니다. 감사도 설명도 이 기록으로 합니다.' },
   { lab: '이관성', t: '담당자가 바뀌어도 *이어집니다*',
     v: '값을 만드는 것이 사람의 감이 아니라 절차입니다. 인수인계 문서가 아니라 코드가 기준입니다.' },
   { lab: '확장성', t: '다른 사업소로 *옮길 수 있습니다*',
     v: '이론 계산식만 갈아끼우면 학습 층과 검증 가드는 그대로 씁니다. 처음부터 다시 만들지 않습니다.' },
  ].forEach((c, i) => {
    const x = i % 2 === 0 ? 72 : 652, y = i < 2 ? 288 : 460;
    d.panel(x, y, 556, 'on');
    d.plab(c.lab, x, y + 14, 556, C.brass);
    d.sub(c.t, x, y + 36, 556, 1);
    d.txt(c.v, x, y + 78, 556, 2);
  });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '이 과제가 바꾼 것은 숫자가 아니라 *숫자를 정하는 방법*입니다.');
};
