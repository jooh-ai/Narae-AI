/* 슬라이드 12 · 시운전 함정 3개 ★
   계획서 §6 '시운전 함정 3건' 그대로. 이 장의 메시지는 발견이 아니라 절차다 —
   데이터를 믿는 것이 아니라 의심하는 절차를 코드에 심었다.                  */
'use strict';
module.exports = (pptx, T) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { sec: '시운전', idx: 5, step: 5 });

  T.title(d, '시운전에서 함정 3개를 만나,', '전부 *코드로 못박았습니다*');
  T.lead(d, '숫자가 자동으로 들어온다는 것은 _틀린 숫자도 자동으로 들어온다_ 는 뜻입니다. 만난 함정을 사람의 주의가 아니라 코드로 막았습니다.');

  const TRAP = [
    { n: '함정 1', t: 'IGV 미실시 회차가\n섞여 들어왔다',
      sym: '3회차가 4~6 MW 낮게 나왔습니다. 그대로 두면 미달로 잘못 판단됩니다.',
      big: '6.0', unit: 'MW', note: '가장 크게 벌어진 폭',
      guard: 'IGV 미실시로 기록된 회차는 _누적 반영을 차단_ 합니다. 값은 남기고 학습에서만 뺍니다.' },
    { n: '함정 2', t: '습도계 값이\n서서히 어긋났다',
      sym: '취득값 19.6% 인데 실제는 68.5% 였습니다. 계기 한 대만 믿으면 못 잡습니다.',
      big: '4.57', unit: 'MW', note: '이 한 건의 오차 폭',
      guard: '습도계 _2대를 교차 확인_ 해 벌어지면 그 회차는 반영 보류하고 화면에 띄웁니다.' },
    { n: '함정 3', t: '대기압 평균 기간이\n신고 서식과 달랐다',
      sym: '우리는 7일 평균, 신고 서식은 5일 평균이었습니다. 조용히 어긋나는 종류입니다.',
      big: '0.5', unit: 'MW', note: '어긋난 폭 (작지만 상시)',
      guard: '서식 수식을 그대로 읽어 대조하는 _자동 시험_ 을 걸어 두었습니다. 다시 어긋나면 실패합니다.' },
  ];
  TRAP.forEach((p, i) => {
    const x = 72 + i * 386;
    d.panel(x, 288, 364, 'bad');
    d.plab(p.n, x, 302, 364, C.red);
    d.sub(p.t, x, 324, 364, 2);
    d.txt(p.sym, x, 392, 364, 3);
    d.zone(x, 470, 364, 62);
    d.bigUnit(p.big, p.unit, x + 16, 482, 26, C.red);
    d.text(p.note, { x: x + 150, y: 490, w: 200, px: 11.5, lh: 1.3, mono: true, color: C.dim2 });
    d.plab('심어 둔 가드', x, 548, 364, C.brass);
    d.txt(p.guard, x, 568, 364, 3);
  });

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '데이터를 믿는 것이 아니라, *의심하는 절차*를 코드에 심었습니다.');
};
