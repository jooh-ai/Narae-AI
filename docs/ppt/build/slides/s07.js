/* 슬라이드 6 · 데이터 — 사람 손을 거치지 않고 가져온다
   취득 항목 6종은 measurements_seed.json 의 필드 그대로다.
   Tool 화면은 최신 캡쳐 미수령 → 규격 맞춘 자리표시자 프레임을 둔다.      */
'use strict';
module.exports = (pptx, T) => {
  const { C, G } = T;
  const { d } = T.shell(pptx, { sec: '데이터', idx: 3, step: 3 });

  T.title(d, '숫자를 사람 손을 거치지 않고,', '*설비에서 바로* 가져옵니다');
  T.lead(d, '운전 서버와 표준 통신으로 직접 연결해 6가지 값을 _1시간 시간가중평균_ 으로 받습니다. 옮겨 적는 단계가 없으니 오타도 없습니다.');

  d.zone(G.L, 288, G.W, 78);
  d.plab('취득 경로', 96, 300, 400);
  [[96, 110, '설비 계측'], [352, 150, '표준 통신 직결'],
   [682, 190, '1시간 시간가중평균'], [1052, 132, '검증 후 누적']]
    .forEach(([x, w, s], i) => d.chip(s, x, 322, w, i === 3));
  [266, 622, 932].forEach(x => d.arrow(x, 329));

  /* 좌 — 취득 항목 6종 */
  d.panel(G.L, 396, 556, null);
  d.plab('받아 오는 값  ·  6가지', G.L, 410, 556);
  d.zone(G.L, 428, 556, 168);
  [['외기온도', '보정값을 고르는 기준'], ['대기압', '이론 출력 계산'],
   ['상대습도', '계기 2대 교차 확인'], ['진공도', '이론 출력 계산'],
   ['발전량', '실적 대조'], ['IGV 실시 여부', '미실시면 반영 차단']]
    .forEach(([k, v], i) => {
      const y = 442 + i * 26;
      d.text(k, { x: G.L + 16, y, w: 150, px: 13.5, lh: 1.3, color: C.ink });
      d.text(v, { x: G.L + 180, y, w: 356, px: 13, lh: 1.3, color: C.dim });
      if (i < 5) d.hline(G.L + 16, y + 22, 524, C.rule2, 1);
    });
  d.txt('_습도는 2대를 함께 봅니다_ — 두 값이 벌어지면 반영을 보류합니다.',
        G.L, 604, 556, 1);

  /* 우 — Tool 화면 자리 */
  d.panel(652, 396, 556, null);
  d.plab('Tool 산정 탭  ·  최신 화면 삽입 자리', 652, 410, 556);
  d.box(652, 428, 524, 168, C.groove, C.rule, 1.5, 'dash');
  d.text('화면 캡쳐를 여기에 넣습니다', { x: 652, y: 490, w: 524, px: 15, lh: 1.4,
                                          color: C.dim2, align: 'center' });
  d.plab('524 × 168 px  ·  가로 5.46 in', 652, 518, 524, C.dim2);
  d.txt('취득 결과 요약줄에 값·시각·검증 통과 여부가 함께 찍힙니다.', 652, 604, 556, 1);

  d.hline(G.L, G.RULE2, G.W, C.rule, 1);
  T.foot(d, '숫자의 출처가 *화면에 그대로 남습니다* — 나중에 왜 그 값이었는지 되짚을 수 있습니다.');
};
